import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const packageRoot = join(import.meta.dirname, "..");
const svgDirectory = join(packageRoot, "src/icons/svg");
const scssOutput = join(packageRoot, "src/theme/_icons.scss");
const namesOutput = join(packageRoot, "src/components/icon/iconNames.ts");

const duotoneSuffix = ".duotone.svg";

function toDataUrl(svg: string) {
    const minified = svg.replace(/\s*\n\s*/g, "").trim();
    // Only the characters CSS url() and data URLs require are escaped, keeping the SVG readable in DevTools
    const escaped = minified.replace(/%/g, "%25").replace(/#/g, "%23").replace(/"/g, "'").replace(/</g, "%3C").replace(/>/g, "%3E");
    return `url("data:image/svg+xml,${escaped}")`;
}

const files = readdirSync(svgDirectory).filter((file) => file.endsWith(".svg"));
const names = files
    .filter((file) => !file.endsWith(duotoneSuffix))
    .map((file) => file.slice(0, -".svg".length))
    .sort();

const declarations = names.flatMap((name) => {
    const lines = [`        --dextinity-icon-${name}: ${toDataUrl(readFileSync(join(svgDirectory, `${name}.svg`), "utf8"))};`];
    if (files.includes(`${name}${duotoneSuffix}`)) {
        lines.push(`        --dextinity-icon-${name}-duotone: ${toDataUrl(readFileSync(join(svgDirectory, `${name}${duotoneSuffix}`), "utf8"))};`);
    }
    return lines;
});

writeFileSync(
    scssOutput,
    `// Generated by \`pnpm run generate:icons\` from src/icons/svg — do not edit.
// A brand replaces an icon by redefining its variable; see the Icons docs.
@layer dextinity {
    :root {
${declarations.join("\n")}
    }
}
`,
);

writeFileSync(
    namesOutput,
    `// Generated by \`pnpm run generate:icons\` from src/icons/svg — do not edit.

export const iconNames = [
${names.map((name) => `    "${name}",`).join("\n")}
] as const;

export type IconName = (typeof iconNames)[number];
`,
);

console.log(`Generated ${names.length} icons`);
